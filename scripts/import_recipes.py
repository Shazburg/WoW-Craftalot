#!/usr/bin/env python3
"""Generate the bundled Azeroth subset from the licensed ProfessionDB archive."""
import argparse
import hashlib
import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFESSIONS = [(197, "Tailoring", 2540), (333, "Enchanting", 2494), (185, "Cooking", 2548)]


def generate(archive):
    with zipfile.ZipFile(archive) as source:
        lines = ["-- Generated by scripts/import_recipes.py; see Data/PROVENANCE.md.",
                 "local _, A = ...", "A.Recipes = {"]
        counts = {}
        for profession, name, skill_line in PROFESSIONS:
            core = source.read(f"ProfessionDB/Data/Retail/_core/{name}.lua").decode("utf-8-sig").replace("\r\n", "\n")
            names = source.read(f"ProfessionDB/Data/Retail/enGB/{name}.lua").decode("utf-8-sig").replace("\r\n", "\n")
            titles = dict(re.findall(r'\[(\d+)\] = \{\s*\["name"\] = ("(?:[^"\\]|\\.)*")', names))
            count = 0
            for spell, body in re.findall(r'\t\t\[(\d+)\] = \{\n(.*?)\n\t\t\},', core, re.S):
                field = lambda key: re.search(r'\["' + key + r'"\] = (\d+)', body)
                if not field("skillLine") or int(field("skillLine").group(1)) != skill_line:
                    continue
                difficulty = re.search(r'\["difficulty"\] = \{(.*?)\}', body, re.S)
                reagents = re.search(r'\["reagents"\] = \{(.*?)\}', body, re.S)
                if not difficulty or not reagents:
                    continue
                tiers = re.findall(r'\d+', difficulty.group(1))
                mats = re.findall(r'\[(\d+)\] = (\d+)', reagents.group(1))
                if len(tiers) != 4 or not mats:
                    continue
                item = field("craftedItemId")
                title = titles.get(spell, json.dumps("Recipe " + spell))
                ingredients = ",".join(f"[{key}]={qty}" for key, qty in mats)
                lines.append(f'  [{spell}]={{id={spell},profession={profession},skillLine={skill_line},name={title},'
                             f'difficulty={{{",".join(tiers)}}},reagents={{{ingredients}}},'
                             f'item={item.group(1) if item else "nil"},quantity=1}},')
                count += 1
            counts[name] = count
        lines.append("}")
        (ROOT / "Data/Recipes.lua").write_text("\n".join(lines) + "\n")
        (ROOT / "licenses/ProfessionDB.txt").write_bytes(source.read("ProfessionDB/LICENSE"))
    return counts


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("archive", type=Path)
    args = parser.parse_args()
    print(generate(args.archive))
    print("Source archive SHA256:", hashlib.sha256(args.archive.read_bytes()).hexdigest())
